"""Build src/match/summoners.gen.ts and scripts/real-dmg.json from the 2026 LCK games (owner: combat-stats session).

Run from anywhere:  python -I scripts/build_combat_ref.py

Source: LoLSim/data/raw/*.json.gz (Riot match data of the LCK games, read-only). Participants 1-5 are blue
Top / Jungle / Mid / Bot / Support, 6-10 red in the same order (tournament data).

Outputs
  src/match/summoners.gen.ts   SUMMONER_PAIRS[champ][role] = most taken pair (>= MIN_GAMES), ROLE_PAIRS[role] fallback
  scripts/real-dmg.json        test reference only (not shipped): per champion damage to champions per minute and its
                               physical / magic / true split; per keystone what the rune produced (var1) per minute
"""
from __future__ import annotations

import collections
import glob
import gzip
import json
import sys
from pathlib import Path

GAME = Path(__file__).resolve().parent.parent
DATA = GAME.parent / "data"
RAW = str(DATA / "raw" / "*.json.gz")
CHAMPS_JSON = GAME / "public" / "data" / "champions.json"
OUT_TS = GAME / "src" / "match" / "summoners.gen.ts"
OUT_REF = GAME / "scripts" / "real-dmg.json"
ROLES = ["Top", "Jungle", "Mid", "Bot", "Support"]
MIN_GAMES = 3
SPELL_NAMES = {1: "cleanse", 3: "exhaust", 4: "flash", 6: "ghost", 7: "heal", 11: "smite", 12: "teleport",
               14: "ignite", 21: "barrier", 32: "mark"}


def main() -> int:
    ids = {c["id"].lower(): c["id"] for c in json.loads(CHAMPS_JSON.read_text(encoding="utf8"))["champions"]}
    pairs: dict[tuple[str, str], collections.Counter] = collections.defaultdict(collections.Counter)
    role_pairs: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    dmg = collections.defaultdict(lambda: {"n": 0, "min": 0.0, "p": 0.0, "m": 0.0, "t": 0.0})
    ks = collections.defaultdict(lambda: {"n": 0, "min": 0.0, "var1": 0.0})
    files = sorted(glob.glob(RAW))
    unknown = collections.Counter()
    for f in files:
        with gzip.open(f, "rt", encoding="utf8") as fh:
            g = json.load(fh)
        d = g.get("data") or {}
        parts = d.get("participants") or []
        if len(parts) != 10:
            continue
        for i, p in enumerate(parts):
            role = ROLES[i % 5]
            cid = ids.get(str(p.get("championName", "")).lower())
            if not cid:
                unknown[p.get("championName")] += 1
                continue
            a, b = p.get("summoner1Id", p.get("spell1Id")), p.get("summoner2Id", p.get("spell2Id"))
            pair = tuple(sorted(SPELL_NAMES.get(x, str(x)) for x in (a, b)))
            pairs[(cid, role)][pair] += 1
            role_pairs[role][pair] += 1
            mins = max(1.0, float(p.get("timePlayed") or d.get("gameDuration") or 1800) / 60)
            r = dmg[cid]
            r["n"] += 1
            r["min"] += mins
            r["p"] += p.get("physicalDamageDealtToChampions") or 0
            r["m"] += p.get("magicDamageDealtToChampions") or 0
            r["t"] += p.get("trueDamageDealtToChampions") or 0
            sel = (((p.get("perks") or {}).get("styles") or [{}])[0].get("selections") or [{}])[0]
            if sel.get("perk"):
                k = ks[str(sel["perk"])]
                k["n"] += 1
                k["min"] += mins
                k["var1"] += sel.get("var1") or 0

    champ_pairs: dict[str, dict[str, list[str]]] = {}
    for (cid, role), cnt in sorted(pairs.items()):
        pair, n = cnt.most_common(1)[0]
        if n >= MIN_GAMES:
            champ_pairs.setdefault(cid, {})[role] = list(pair)
    role_default = {r: list(role_pairs[r].most_common(1)[0][0]) for r in ROLES if role_pairs[r]}

    lines = [
        "// GENERATED by scripts/build_combat_ref.py from the 2026 LCK games (data/raw). Do not edit by hand.",
        "// Summoner spells each champion takes in each role (most taken pair, at least "
        f"{MIN_GAMES} games); ROLE_PAIRS otherwise.",
        "",
        "export type SummonerName = " + " | ".join(json.dumps(v) for v in sorted(set(SPELL_NAMES.values()))) + ";",
        "",
        f"export const ROLE_PAIRS: Record<string, SummonerName[]> = {json.dumps(role_default, separators=(',', ':'))};",
        "",
        "export const SUMMONER_PAIRS: Record<string, Record<string, SummonerName[]>> = {",
    ]
    for cid in sorted(champ_pairs):
        lines.append(f"  {json.dumps(cid)}: {json.dumps(champ_pairs[cid], separators=(',', ':'))},")
    lines += ["};", ""]
    OUT_TS.write_text("\n".join(lines), encoding="utf8", newline="\n")

    ref = {
        "games": len(files),
        "champions": {
            cid: {
                "games": r["n"],
                "perMin": round((r["p"] + r["m"] + r["t"]) / r["min"], 1),
                "share": [round(r["p"] / max(1, r["p"] + r["m"] + r["t"]), 3), round(r["m"] / max(1, r["p"] + r["m"] + r["t"]), 3),
                          round(r["t"] / max(1, r["p"] + r["m"] + r["t"]), 3)],
            }
            for cid, r in sorted(dmg.items())
        },
        "keystones": {k: {"games": v["n"], "var1PerMin": round(v["var1"] / max(1, v["min"]), 1)} for k, v in sorted(ks.items())},
        "rolePairs": role_default,
    }
    OUT_REF.write_text(json.dumps(ref, ensure_ascii=False, indent=1), encoding="utf8", newline="\n")
    print(f"{len(files)} games; {sum(len(v) for v in champ_pairs.values())} champion-role pairs; role defaults {role_default}")
    if unknown:
        print("champion names not matched:", dict(unknown))
    print("keystones var1/min:", {k: v["var1PerMin"] for k, v in ref["keystones"].items()})
    return 0


if __name__ == "__main__":
    sys.exit(main())
